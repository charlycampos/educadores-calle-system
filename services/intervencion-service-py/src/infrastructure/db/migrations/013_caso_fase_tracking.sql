-- 0. Restricciones sobre FASE: debe quedar solo CK_NNA_CASO_FASE con el
--    vocabulario nuevo. Si aparece CHK_FASE, el paso 2 no se ejecutó.
SELECT CONSTRAINT_NAME, SEARCH_CONDITION_VC
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'SEC_USER'
   AND TABLE_NAME = 'NNA_CASO'
   AND CONSTRAINT_TYPE = 'C'
   AND UPPER(SEARCH_CONDITION_VC) LIKE '%FASE%';

-- 1. Distribución de fases tras el backfill
SELECT FASE, COUNT(*) AS CANTIDAD
  FROM SEC_USER.NNA_CASO
 GROUP BY FASE
 ORDER BY FASE;

-- 2. Historial reconstruido
SELECT FASE, ESTADO, COUNT(*) AS CANTIDAD
  FROM SEC_USER.CASO_FASE
 GROUP BY FASE, ESTADO
 ORDER BY FASE, ESTADO;

-- 3. Coherencia: la fase vigente de CASO_FASE debe coincidir con NNA_CASO.FASE.
--    Esta consulta debe devolver CERO filas.
SELECT c.ID, c.CODIGO_CASO, c.FASE AS FASE_CASO, f.FASE AS FASE_VIGENTE
  FROM SEC_USER.NNA_CASO c
  JOIN SEC_USER.CASO_FASE f ON f.CASO_ID = c.ID AND f.FECHA_FIN IS NULL
 WHERE c.FASE <> f.FASE
   AND c.FASE <> 'EGRESADO';

-- 4. Fases vencidas hoy — el semáforo que alimentará las alertas
SELECT f.FASE,
       COUNT(*) AS VENCIDAS,
       ROUND(AVG(MONTHS_BETWEEN(SYSDATE, f.FECHA_INICIO)), 1) AS MESES_PROMEDIO
  FROM SEC_USER.CASO_FASE f
  JOIN SEC_USER.NNA_CASO c ON c.ID = f.CASO_ID
 WHERE f.FECHA_FIN IS NULL
   AND c.ESTADO <> 'CERRADO'
   AND ADD_MONTHS(f.FECHA_INICIO, f.PLAZO_MESES + f.MESES_EXTENSION) < SYSDATE
 GROUP BY f.FASE
 ORDER BY f.FASE;
